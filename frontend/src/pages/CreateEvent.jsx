import { useState } from 'react';
import { Link } from 'react-router-dom';
import apiClient from '../api/client';
import { useAuth } from '../context/AuthContext';
import { generatePosterSvgDataUrl, CMCU_UNITS } from './EventList';
import { generateStandardEventTasks, TASKS_STORAGE_KEY } from './ManageTasks';

const STANDARD_CMCU_LOCATIONS = [
    'Hội trường A - CS1 Vạn Phúc',
    'Hội trường lớn - Tòa nhà CMC',
    'Phòng Lab 302 - CS1',
    'Sảnh Tây CMC - Cơ sở 1',
    'Hội trường Cơ sở Tây Mỗ'
];

function CreateEvent() {
    const { user } = useAuth();
    const currentRole = (user?.system_role || user?.role || '').toString().toUpperCase();
    const isStaff = currentRole === 'STAFF';

    const [formData, setFormData] = useState({
        title: '',
        description: '',
        location: 'Hội trường A - CS1 Vạn Phúc',
        start_time: '',
        end_time: '',
        seat_capacity: 100
    });

    const [category, setCategory] = useState('Hội thảo & Công nghệ');
    const [faculty, setFaculty] = useState('Khoa CNTT & Truyền thông');
    const [guest, setGuest] = useState('');
    const [customBannerUrl, setCustomBannerUrl] = useState('');
    const [posterThemeIndex, setPosterThemeIndex] = useState(0);
    const [autoCreateTasks, setAutoCreateTasks] = useState(true);

    const [selectedCohorts, setSelectedCohorts] = useState(['K1']);
    const [isAllSchool, setIsAllSchool] = useState(false);
    const [msg, setMsg] = useState('');
    const [submitting, setSubmitting] = useState(false);

    const handleChange = (e) => setFormData({ ...formData, [e.target.name]: e.target.value });

    const handleCohortToggle = (cohort) => {
        if (selectedCohorts.includes(cohort)) {
            setSelectedCohorts(selectedCohorts.filter((c) => c !== cohort));
        } else {
            setSelectedCohorts([...selectedCohorts, cohort]);
        }
    };

    const handleBannerFileUpload = (e) => {
        const file = e.target.files?.[0];
        if (!file) return;

        const reader = new FileReader();
        reader.onload = (event) => {
            const img = new Image();
            img.onload = () => {
                const canvas = document.createElement('canvas');
                const maxWidth = 800;
                const scale = img.width > maxWidth ? maxWidth / img.width : 1;
                canvas.width = img.width * scale;
                canvas.height = img.height * scale;
                const ctx = canvas.getContext('2d');
                ctx.drawImage(img, 0, 0, canvas.width, canvas.height);
                setCustomBannerUrl(canvas.toDataURL('image/jpeg', 0.78));
            };
            img.src = event.target.result;
        };
        reader.readAsDataURL(file);
    };

    const autoGeneratedBanner = generatePosterSvgDataUrl({
        title: formData.title || 'Tên sự kiện sẽ hiển thị tại đây',
        category,
        faculty,
        guest: guest || 'Ban Chủ nhiệm Khoa & Diễn giả CMCU',
        location: formData.location || 'Đại học CMC',
        startTime: formData.start_time || new Date().toISOString(),
        themeIndex: posterThemeIndex
    });

    const previewBannerSrc = customBannerUrl.trim() || autoGeneratedBanner;

    const handleCycleAutoPoster = () => {
        setCustomBannerUrl('');
        setPosterThemeIndex((prev) => (prev + 1) % 5);
    };

    const handleSubmit = async (e) => {
        e.preventDefault();
        setMsg('');

        const rawTitle = formData.title.trim();
        if (rawTitle.length < 5) {
            setMsg('❌ Tên sự kiện quá ngắn (tối thiểu 5 ký tự) và cần mô tả rõ nội dung.');
            return;
        }

        const normalizedTitle = rawTitle.charAt(0).toUpperCase() + rawTitle.slice(1);

        const rawLocation = formData.location.trim();
        if (!rawLocation) {
            setMsg('❌ Vui lòng nhập hoặc chọn địa điểm tổ chức.');
            return;
        }
        const normalizedLocation = rawLocation.charAt(0).toUpperCase() + rawLocation.slice(1);

        if (!formData.start_time || !formData.end_time) {
            setMsg('❌ Vui lòng chọn đầy đủ thời gian bắt đầu và kết thúc.');
            return;
        }
        const start = new Date(formData.start_time);
        const end = new Date(formData.end_time);
        if (end <= start) {
            setMsg('❌ Lỗi: Thời gian kết thúc phải diễn ra SAU thời gian bắt đầu.');
            return;
        }

        const startHour = start.getHours();
        const endHour = end.getHours();
        if (startHour < 6 || startHour >= 22 || endHour > 22) {
            setMsg('❌ Khung giờ không hợp lệ: Sự kiện sinh viên phải diễn ra trong khoảng 06:00 – 22:00.');
            return;
        }

        const cap = Number(formData.seat_capacity);
        if (cap < 5) {
            setMsg('❌ Số lượng ghế tối thiểu phải từ 5 chỗ trở lên.');
            return;
        }
        if (normalizedLocation.toLowerCase().includes('hội trường') && cap < 20) {
            setMsg('❌ Địa điểm là Hội trường lớn nhưng sức chứa dưới 20 chỗ là chưa hợp lý. Vui lòng tăng sức chứa hoặc chọn Phòng học/Lab.');
            return;
        }

        if (!isAllSchool && selectedCohorts.length === 0) {
            setMsg('❌ Vui lòng chọn ít nhất 1 Khóa hoặc chọn "Mở cho toàn trường".');
            return;
        }

        setSubmitting(true);
        try {
            let eligibility = [];
            if (!isAllSchool) {
                eligibility = selectedCohorts.map((cohort) => ({
                    cohort: cohort,
                    faculty_id: null
                }));
            }

            const res = await apiClient.post('/admin/events', {
                ...formData,
                title: normalizedTitle,
                location: normalizedLocation,
                seat_capacity: cap,
                admin_user_id: user?.user_id,
                eligibility
            });

            if (res.data.success) {
                let createdId = res.data?.data?.event_id || res.data?.event_id || res.data?.id;

                if (!createdId) {
                    const listRes = await apiClient.get('/events');
                    const list = Array.isArray(listRes.data)
                        ? listRes.data
                        : (listRes.data?.data || listRes.data?.events || []);
                    const matched = list
                        .filter((item) => item.title === normalizedTitle)
                        .sort((a, b) => b.event_id - a.event_id)[0];
                    createdId = matched?.event_id;
                }

                if (createdId) {
                    try {
                        const savedMap = JSON.parse(localStorage.getItem('cmcu_event_custom_meta') || '{}');
                        savedMap[createdId] = {
                            category,
                            faculty,
                            guest: guest.trim() || 'Ban tổ chức & Khách mời CMCU',
                            banner_url: customBannerUrl.trim() || ''
                        };
                        localStorage.setItem('cmcu_event_custom_meta', JSON.stringify(savedMap));
                    } catch {

                    }

                    if (isStaff && autoCreateTasks) {
                        try {
                            const existingTasks = JSON.parse(localStorage.getItem(TASKS_STORAGE_KEY) || '[]');
                            const newChecklist = generateStandardEventTasks(
                                createdId,
                                normalizedTitle,
                                formData.start_time,
                                user?.full_name || 'Staff Test'
                            );
                            localStorage.setItem(
                                TASKS_STORAGE_KEY,
                                JSON.stringify([...newChecklist, ...existingTasks])
                            );
                            window.dispatchEvent(new Event('cmcu_tasks_updated'));
                        } catch {

                        }
                    }
                }

                setMsg(
                    isStaff && autoCreateTasks
                        ? '✅ Tạo sự kiện & tự động khởi tạo bộ 7 Task vận hành thành công!'
                        : '✅ Tạo sự kiện & Banner thành công!'
                );
                setFormData({
                    title: '',
                    description: '',
                    location: 'Hội trường A - CS1 Vạn Phúc',
                    start_time: '',
                    end_time: '',
                    seat_capacity: 100
                });
                setGuest('');
                setCustomBannerUrl('');
            } else {
                setMsg('❌ ' + (res.data.message || 'Có lỗi xảy ra khi tạo sự kiện.'));
            }
        } catch (error) {
            setMsg('❌ Lỗi: ' + (error.response?.data?.message || error.message));
        } finally {
            setSubmitting(false);
        }
    };

    return (
        <div className="admin-dashboard-container">
            <div className="bg-orb orb-1"></div>
            <div className="bg-orb orb-2"></div>

            <div className="form-center-wrapper">
                <div className="premium-form-card">
                    <div className="form-header-area">
                        <div className="form-icon-badge">
                            <span>➕</span>
                        </div>
                        <div>
                            <h2 className="form-main-title">Tạo Sự Kiện Mới</h2>
                            <p className="form-sub-title">Điền thông tin chi tiết để khởi tạo sự kiện và Banner hiển thị.</p>
                        </div>
                    </div>

                    {msg && (
                        <div
                            className={`custom-toast ${msg.includes('❌') ? 'toast-error' : 'toast-success'}`}
                            style={{ marginBottom: '24px', position: 'relative', zIndex: 10, display: 'flex', justifyContent: 'space-between', alignItems: 'center', gap: '12px', flexWrap: 'wrap' }}
                        >
                            <span>{msg}</span>
                            {msg.includes('✅') && (
                                <div style={{ display: 'flex', gap: '14px' }}>
                                    {isStaff && autoCreateTasks && (
                                        <Link to="/admin/tasks" style={{ color: 'inherit', fontWeight: 800, textDecoration: 'underline' }}>
                                            Xem 7 Task vừa tạo →
                                        </Link>
                                    )}
                                    <Link to="/" style={{ color: 'inherit', fontWeight: 800, textDecoration: 'underline' }}>
                                        Xem trang chủ →
                                    </Link>
                                </div>
                            )}
                        </div>
                    )}

                    <form onSubmit={handleSubmit}>
                        <div className="form-section">
                            <h3 className="form-section-title">📌 Thông tin chung</h3>
                            <div className="form-grid">
                                <div className="input-group">
                                    <label className="input-label">Tên sự kiện</label>
                                    <input
                                        name="title"
                                        className="input-premium"
                                        placeholder="VD: Hội thảo AI & Ứng dụng trong Doanh nghiệp"
                                        value={formData.title}
                                        onChange={handleChange}
                                        required
                                    />
                                </div>
                                <div className="input-group">
                                    <label className="input-label">Địa điểm (Chọn gợi ý hoặc nhập)</label>
                                    <input
                                        name="location"
                                        list="cmcu-venues-datalist"
                                        className="input-premium"
                                        placeholder="VD: Hội trường A - CS1 Vạn Phúc"
                                        value={formData.location}
                                        onChange={handleChange}
                                        required
                                    />
                                    <datalist id="cmcu-venues-datalist">
                                        {STANDARD_CMCU_LOCATIONS.map((loc) => (
                                            <option key={loc} value={loc} />
                                        ))}
                                    </datalist>
                                </div>
                            </div>

                            <div className="form-grid" style={{ marginTop: '14px' }}>
                                <div className="input-group">
                                    <label className="input-label">Loại sự kiện</label>
                                    <select
                                        className="input-premium"
                                        value={category}
                                        onChange={(e) => setCategory(e.target.value)}
                                    >
                                        <option value="Hội thảo & Công nghệ">Hội thảo &amp; Công nghệ</option>
                                        <option value="Workshop & Trải nghiệm">Workshop &amp; Trải nghiệm</option>
                                        <option value="Văn nghệ & Lễ kỷ niệm">Văn nghệ &amp; Lễ kỷ niệm</option>
                                        <option value="Giao lưu Sinh viên">Giao lưu Sinh viên</option>
                                        <option value="Cuộc thi Học thuật">Cuộc thi Học thuật</option>
                                    </select>
                                </div>
                                <div className="input-group">
                                    <label className="input-label">Khoa / Đơn vị tổ chức tại CMCU</label>
                                    <select
                                        className="input-premium"
                                        value={faculty}
                                        onChange={(e) => setFaculty(e.target.value)}
                                    >
                                        {CMCU_UNITS.map((unit) => (
                                            <option key={unit.id} value={unit.name}>
                                                {unit.name}
                                            </option>
                                        ))}
                                    </select>
                                </div>
                            </div>

                            <div className="input-group" style={{ marginTop: '14px' }}>
                                <label className="input-label">Khách mời / Diễn giả</label>
                                <input
                                    className="input-premium"
                                    placeholder="VD: TS. Nguyễn Văn A - Chuyên gia AI..."
                                    value={guest}
                                    onChange={(e) => setGuest(e.target.value)}
                                />
                            </div>

                            <div className="input-group" style={{ marginTop: '14px' }}>
                                <label className="input-label">Mô tả chi tiết sự kiện</label>
                                <textarea
                                    name="description"
                                    className="input-premium"
                                    rows="3"
                                    placeholder="Nhập nội dung giới thiệu, lịch trình chi tiết..."
                                    value={formData.description}
                                    onChange={handleChange}
                                    style={{ resize: 'vertical' }}
                                />
                            </div>
                        </div>

                        <div className="form-section">
                            <h3 className="form-section-title">🖼️ Hình ảnh Banner sự kiện</h3>

                            <div style={{ display: 'flex', gap: '10px', flexWrap: 'wrap', alignItems: 'center', marginBottom: '12px' }}>
                                <label
                                    style={{
                                        padding: '9px 14px',
                                        borderRadius: '10px',
                                        background: '#f1f5f9',
                                        border: '1px solid #cbd5e1',
                                        color: '#0f172a',
                                        fontWeight: 700,
                                        fontSize: '0.88rem',
                                        cursor: 'pointer'
                                    }}
                                >
                                    📁 Tải ảnh từ máy tính
                                    <input
                                        type="file"
                                        accept="image/*"
                                        onChange={handleBannerFileUpload}
                                        style={{ display: 'none' }}
                                    />
                                </label>

                                <button
                                    type="button"
                                    onClick={handleCycleAutoPoster}
                                    style={{
                                        padding: '9px 14px',
                                        borderRadius: '10px',
                                        border: 'none',
                                        background: 'linear-gradient(135deg, #2563eb 0%, #7c3aed 100%)',
                                        color: '#ffffff',
                                        fontWeight: 700,
                                        fontSize: '0.88rem',
                                        cursor: 'pointer'
                                    }}
                                >
                                    🎨 Tự tạo Banner theo tên (Đổi màu)
                                </button>

                                {customBannerUrl && (
                                    <button
                                        type="button"
                                        onClick={() => setCustomBannerUrl('')}
                                        style={{
                                            padding: '9px 12px',
                                            borderRadius: '10px',
                                            border: '1px solid #fca5a5',
                                            background: '#fef2f2',
                                            color: '#b91c1c',
                                            fontWeight: 700,
                                            fontSize: '0.84rem',
                                            cursor: 'pointer'
                                        }}
                                    >
                                        ✕ Xóa ảnh đã chọn
                                    </button>
                                )}
                            </div>

                            <div className="input-group" style={{ marginBottom: '14px' }}>
                                <input
                                    className="input-premium"
                                    placeholder="Hoặc dán đường dẫn ảnh (https://...) — để trống sẽ dùng ảnh tự tạo bên dưới"
                                    value={customBannerUrl}
                                    onChange={(e) => setCustomBannerUrl(e.target.value)}
                                />
                            </div>

                            <div
                                style={{
                                    borderRadius: '16px',
                                    overflow: 'hidden',
                                    border: '2px solid rgba(79, 70, 229, 0.25)',
                                    boxShadow: '0 10px 25px rgba(0,0,0,0.15)',
                                    aspectRatio: '16 / 9',
                                    background: '#0f172a'
                                }}
                            >
                                <img
                                    src={previewBannerSrc}
                                    alt="Banner Preview"
                                    style={{ width: '100%', height: '100%', objectFit: 'cover', display: 'block' }}
                                />
                            </div>
                        </div>

                        <div className="form-section">
                            <h3 className="form-section-title">⏱️ Thời gian (06:00 – 22:00) &amp; Số lượng ghế</h3>
                            <div className="form-grid">
                                <div className="input-group">
                                    <label className="input-label">Bắt đầu</label>
                                    <input
                                        type="datetime-local"
                                        name="start_time"
                                        className="input-premium"
                                        value={formData.start_time}
                                        onChange={handleChange}
                                        required
                                    />
                                </div>
                                <div className="input-group">
                                    <label className="input-label">Kết thúc</label>
                                    <input
                                        type="datetime-local"
                                        name="end_time"
                                        className="input-premium"
                                        value={formData.end_time}
                                        onChange={handleChange}
                                        required
                                    />
                                </div>
                            </div>
                            <div className="form-grid" style={{ marginTop: '14px' }}>
                                <div className="input-group">
                                    <label className="input-label">Số lượng ghế (Tối thiểu 20 nếu là Hội trường)</label>
                                    <input
                                        type="number"
                                        name="seat_capacity"
                                        min="5"
                                        className="input-premium"
                                        value={formData.seat_capacity}
                                        onChange={handleChange}
                                        required
                                    />
                                </div>
                                <div></div>
                            </div>
                        </div>

                        <div className="form-section">
                            <h3 className="form-section-title">🔒 Điều kiện tham gia</h3>

                            <label className="checkbox-premium">
                                <input
                                    type="checkbox"
                                    checked={isAllSchool}
                                    onChange={(e) => setIsAllSchool(e.target.checked)}
                                />
                                <span className="checkmark"></span>
                                <span className="checkbox-text">Mở cho toàn trường (Mọi khóa)</span>
                            </label>

                            {!isAllSchool && (
                                <div className="cohort-area" style={{ animation: 'slideUpFade 0.3s ease' }}>
                                    <p className="cohort-hint">Chọn các Khóa được phép tham gia:</p>
                                    <div className="cohort-pills">
                                        {['K1', 'K2', 'K3', 'K4'].map((cohort) => {
                                            const isSelected = selectedCohorts.includes(cohort);
                                            return (
                                                <button
                                                    key={cohort}
                                                    type="button"
                                                    className={`cohort-pill ${isSelected ? 'active' : ''}`}
                                                    onClick={() => handleCohortToggle(cohort)}
                                                >
                                                    {isSelected && '✓ '} {cohort}
                                                </button>
                                            );
                                        })}
                                    </div>
                                </div>
                            )}
                        </div>

                        {isStaff && (
                            <div
                                className="form-section"
                                style={{
                                    background: 'rgba(45, 194, 117, 0.1)',
                                    border: '1px solid rgba(45, 194, 117, 0.35)',
                                    borderRadius: '14px',
                                    padding: '16px'
                                }}
                            >
                                <label className="checkbox-premium" style={{ marginBottom: '6px' }}>
                                    <input
                                        type="checkbox"
                                        checked={autoCreateTasks}
                                        onChange={(e) => setAutoCreateTasks(e.target.checked)}
                                    />
                                    <span className="checkmark"></span>
                                    <span className="checkbox-text" style={{ fontWeight: 700, color: '#6ee7b7' }}>
                                        ⚡ Tự động khởi tạo bộ 7 Task vận hành chuẩn (T-Minus) cho sự kiện này
                                    </span>
                                </label>
                                <p style={{ margin: '0 0 0 34px', fontSize: '0.84rem', color: '#cbd5e1' }}>
                                    Tự chia các mốc: Truyền thông (T-5d), In ấn (T-2d), Chốt DS &amp; Set-up (T-1d), Test kỹ thuật (T-90m), Check-in (T-30m) và Tổng kết (T+1d).
                                </p>
                            </div>
                        )}

                        <div className="form-actions">
                            <button type="submit" className="btn-submit-premium" disabled={submitting}>
                                {submitting ? '⏳ Đang tạo sự kiện...' : '🚀 Tạo Sự Kiện'}
                            </button>
                        </div>
                    </form>
                </div>
            </div>
        </div>
    );
}

export default CreateEvent;